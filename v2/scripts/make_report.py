"""Fill the report with the results of the executed notebooks and compile it.

Reads ``data/processed/results_0{1,2,3}.json`` (written by the last cell of each
notebook), writes ``report/results.tex`` (LaTeX macros) and
``report/vs_table.tex``, then runs latexmk if it is installed.

    python make_report.py
"""
from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

V2 = Path(__file__).resolve().parents[1]
REPORT = V2 / "report"


def fmt(x, nd: int = 1) -> str:
    """Number for LaTeX: thousands separators, proper minus sign."""
    if isinstance(x, int) or (isinstance(x, float) and nd == 0):
        s = f"{int(round(x)):,}".replace(",", "{,}")
    else:
        s = f"{x:,.{nd}f}".replace(",", "{,}")
    return s.replace("-", "$-$")


def main() -> int:
    r1, r2, r3 = (json.loads((V2 / "data" / "processed" / f"results_0{i}.json").read_text()) for i in (1, 2, 3))
    m = {
        "NnetPM": fmt(r3["n_pm"]), "NnetOz": fmt(r3["n_o3"]),
        "ValOzN": fmt(r1["val_oz_n"]), "ValPMwithin": fmt(r1["val_pm_within"], 2),
        "VoneGood": fmt(r1["v1_good"], 0), "VtwoGood": fmt(r1["v2_good"], 0),
        "FlagOz": fmt(r1["flag_oz"]), "FlagPM": fmt(r1["flag_pm"]), "StableRatio": fmt(r1["stable_ratio"], 2),
        "CorrBefore": fmt(r1["corr_before"], 2), "CorrAfter": fmt(r1["corr_after"], 2),
        "FillRtwoPM": fmt(r1["fill_r2_pm"], 2), "FillRtwoOz": fmt(r1["fill_r2_oz"], 2),
        "RawCov": fmt(r1["raw_cov"], 0), "CatAcc": fmt(r1["cat_acc"], 0), "CatAccPers": fmt(r1["cat_acc_pers"], 0),
        "ShareGoodTwelve": fmt(r1["share_good_2012"], 0), "ShareGoodTwentyFour": fmt(r1["share_good_2024"], 0),
        "ShareGoodEEA": fmt(r1["share_good_eea"], 0), "WhoMin": fmt(r1["who_min"]), "WhoMax": fmt(r1["who_max"]),
        "TrendPM": fmt(r1["trend_pm"], 2), "TrendOz": fmt(r1["trend_oz"], 2), "TrendOzPct": fmt(r1["trend_oz_pct"], 1),
        "TrendOzP": "$<0.001$" if r1["trend_oz_p"] < 0.001 else f"$= {r1['trend_oz_p']:.3f}$",
        "WorstPM": fmt(r1["worst_pm"], 0), "WorstAQI": fmt(r1["worst_aqi"]), "SecondAQI": fmt(r1["second_aqi"]),
        "FireworksPM": fmt(r1["fireworks_pm"], 1),
        "CovidNOtwo": fmt(abs(r1["covid_no2"]), 0), "CovidPM": fmt(abs(r1["covid_pm"]), 0),
        "PlaceboNOmin": fmt(r1["placebo_no2_min"], 0), "PlaceboNOmax": fmt(r1["placebo_no2_max"], 0),
        "PlaceboPMmin": fmt(r1["placebo_pm_min"], 0), "PlaceboPMmax": fmt(r1["placebo_pm_max"], 0),
        "LiveDate": r1["live_date"], "LiveAQI": fmt(r1["live_aqi"]), "LiveCat": r1["live_cat"],
        "LowCostExact": fmt(r2["lowcost_exact"], 0), "LowCostOne": fmt(r2["lowcost_one"], 0),
        "VoneRFmae": fmt(r2["v1_rf_mae"], 1), "BenzeneRtwo": fmt(r2["benzene_r2"], 5),
        "GeoPMgp": fmt(r3["geo_pm_gp_rmse"], 2), "GeoPMgpR": fmt(r3["geo_pm_gp_r2"], 2),
        "GeoOzbest": fmt(r3["geo_oz_best_rmse"], 2), "GeoOzbestR": fmt(r3["geo_oz_best_r2"], 2),
        "PopPM": fmt(r3["pop_pm"], 1), "PopRatio": fmt(r3["pop_ratio"], 1),
    }
    for target, tag in (("pm25", "PM"), ("o3", "Oz")):
        for setting, stag in (("op", "op"), ("wx", "wx")):
            d = r1[f"fc_{target}_{setting}"]
            m[f"Fc{tag}{stag}MAE"] = fmt(d["mae"], 2)
            m[f"Fc{tag}{stag}SkP"] = fmt(d["skill_pers"], 0)
            m[f"Fc{tag}{stag}SkC"] = fmt(d["skill_clim"], 0)
            m[f"Fc{tag}{stag}Cov"] = fmt(d["cov"], 0)
    lines = ["% generated by scripts/make_report.py from data/processed/results_0*.json; do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()]
    (REPORT / "results.tex").write_text("\n".join(lines) + "\n")

    names = {"co_gt": "CO", "no2_gt": "NO$_2$", "nox_gt": "NO$_x$"}
    rows = []
    for key, vals in r2["vs_r2"].items():
        target, model = key.split("|")
        cells = " & ".join(fmt(vals[s], 2) for s in ("static", "quarterly", "monthly", "weekly"))
        rows.append(f"{names[target]} & {'LightGBM' if model == 'lightgbm' else 'linear'} & {cells}\\\\")
    table = ["\\begin{tabular}{llcccc}", "\\toprule",
             "Target & Model & static & quarterly & monthly & weekly\\\\", "\\midrule", *rows,
             "\\bottomrule", "\\end{tabular}"]
    (REPORT / "vs_table.tex").write_text("\n".join(table) + "\n")
    print(f"wrote {len(m)} macros and {len(rows)} table rows")

    if shutil.which("latexmk"):
        cmd = ["latexmk", "-pdf", "-interaction=nonstopmode", "-halt-on-error", "AQI_v2_report.tex"]
        res = subprocess.run(cmd, cwd=REPORT, capture_output=True, text=True)
        print(res.stdout[-1500:] if res.returncode else "report compiled: report/AQI_v2_report.pdf")
        subprocess.run(["latexmk", "-c"], cwd=REPORT, capture_output=True)
        return res.returncode
    print("latexmk not found: compile report/AQI_v2_report.tex with pdflatex + bibtex")
    return 0


if __name__ == "__main__":
    sys.exit(main())
